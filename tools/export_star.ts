// Sample the retail driver's shared Star CLR0. The original game applies this
// first-material C1 track to the driver, vehicle body and all wheel materials.
import fs from 'node:fs';
import crypto from 'node:crypto';
import {parse,AnimatableColor} from '../vendor/noclip/src/rres/brres.js';
import ArrayBufferSlice from '../vendor/noclip/src/ArrayBufferSlice.js';
const source=process.argv[2]??'assets/common/driver.brres';
const output=process.argv[3]??'include/mkw/star_colors.hpp';
const data=fs.readFileSync(source);
const archive=parse(new ArrayBufferSlice(data.buffer,data.byteOffset,data.byteLength));
const clip=archive.clr0.find(c=>c.name==='star');
if(!clip||clip.loopMode!==1)throw new Error('Missing looping retail star CLR0');
const tracks=clip.matAnimations.map(m=>m.clrAnimations[AnimatableColor.C1]);
if(!tracks.length||tracks.some(t=>!t||t.mask!==255||t.frames.length!==clip.duration+1))throw new Error('Unexpected Star track layout');
const frames=Array.from(tracks[0].frames);
if(tracks.some(t=>t.frames.some((v,i)=>v!==frames[i])))throw new Error('Star material tracks differ');
if(frames[0]!==frames.at(-1))throw new Error('Star loop must close');
const hash=crypto.createHash('sha256').update(data).digest('hex');
const rows=[];for(let i=0;i<frames.length;i+=8)rows.push('    '+frames.slice(i,i+8).map(v=>'0x'+v.toString(16).padStart(8,'0')+'u').join(',')+',');
fs.writeFileSync(output,['#pragma once','#include <array>','#include <cstdint>','namespace mkw {',
    '// Generated by tools/export_star.ts from user-supplied assets/common/driver.brres.',
    '// Source SHA256 '+hash,'// CLR0 star / C1. RRGGBBAA; source mask preserves material alpha.',
    `inline constexpr unsigned StarColorPeriod=${clip.duration};`,
    `inline constexpr std::array<uint32_t,${frames.length}> StarColors{{`,...rows,'}};','}',''].join('\n'));
console.log(JSON.stringify({source,sha256:hash,clip:clip.name,duration:clip.duration,frames:frames.length,mask:tracks[0].mask,materials:clip.matAnimations.map(m=>m.materialName),output}));
